import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';

const run = (cmd, args) => {
  console.log(`> ${cmd} ${args.join(' ')}`);
  const result = spawnSync(cmd, args, {
    stdio: 'inherit',
    shell: process.platform === 'win32',
  });
  if (result.status !== 0) process.exit(result.status ?? 1);
};

const walk = (dir, predicate, found = []) => {
  if (!existsSync(dir)) return found;
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    const stat = statSync(full);
    if (stat.isDirectory()) walk(full, predicate, found);
    else if (predicate(full, name)) found.push(full);
  }
  return found;
};

// 1) Build the real Vinext/Cloudflare output first.
run('pnpm', ['exec', 'vinext', 'build']);

const projectRoot = resolve('.');
const distDir = resolve('dist');
const clientDir = resolve('dist/client');

if (!existsSync(clientDir)) {
  console.error('Deploy aborted: vinext build did not create dist/client.');
  process.exit(1);
}

// 2) Find the Worker output generated by @cloudflare/vite-plugin.
const generatedConfigs = walk(
  distDir,
  (_full, name) => name === 'wrangler.json' || name === 'wrangler.jsonc',
);

const workerEntries = walk(
  distDir,
  (full, name) =>
    name === 'index.js' &&
    !full.includes(`${join('dist', 'client')}`) &&
    !full.includes(`${join('dist', 'server', 'ssr')}`),
);

let generatedConfigPath = generatedConfigs[0] ?? null;
let generated = {};

if (generatedConfigPath) {
  try {
    generated = JSON.parse(readFileSync(generatedConfigPath, 'utf8'));
  } catch {
    console.warn(`Could not parse generated config ${generatedConfigPath}; using a clean deploy config.`);
    generated = {};
  }
}

let workerEntry = null;
if (generatedConfigPath) {
  const besideConfig = resolve(dirname(generatedConfigPath), 'index.js');
  if (existsSync(besideConfig)) workerEntry = besideConfig;
}
workerEntry ??= workerEntries[0] ?? null;

if (!workerEntry) {
  console.error('Deploy aborted: no generated Cloudflare Worker index.js found under dist/.');
  console.error('Generated wrangler configs:', generatedConfigs);
  process.exit(1);
}

// 3) Create a fresh Wrangler config at project root. This avoids the beta Vinext
// generated-config bug where assets.directory can be omitted or resolved incorrectly.
const mainPath = `./${relative(projectRoot, workerEntry).replaceAll('\\', '/')}`;
const assetsPath = './dist/client';

const deployConfig = {
  ...generated,
  $schema: './node_modules/wrangler/config-schema.json',
  name: generated.name || 'macakes',
  main: mainPath,
  compatibility_date: generated.compatibility_date || '2026-09-10',
  compatibility_flags: Array.from(
    new Set([...(generated.compatibility_flags ?? []), 'nodejs_compat']),
  ),
  assets: {
    ...(generated.assets ?? {}),
    directory: assetsPath,
    binding: generated.assets?.binding || 'ASSETS',
  },
};

const deployConfigPath = resolve('wrangler.deploy.json');
writeFileSync(deployConfigPath, `${JSON.stringify(deployConfig, null, 2)}\n`);

console.log('Cloudflare deploy config created:');
console.log(`  worker: ${mainPath}`);
console.log(`  assets: ${assetsPath}`);
console.log(`  config: ${deployConfigPath}`);

if (!existsSync(workerEntry) || !existsSync(clientDir)) {
  console.error('Deploy aborted: Worker or static asset directory is missing.');
  process.exit(1);
}

// 4) Deploy only with the explicit config. No static-directory auto detection.
run('pnpm', ['exec', 'wrangler', 'deploy', '--config', deployConfigPath]);
