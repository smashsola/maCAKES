import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';

const run = (cmd, args) => {
  const result = spawnSync(cmd, args, { stdio: 'inherit', shell: process.platform === 'win32' });
  if (result.status !== 0) process.exit(result.status ?? 1);
};

const findWranglerConfigs = (dir, found = []) => {
  if (!existsSync(dir)) return found;
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    const stat = statSync(full);
    if (stat.isDirectory()) findWranglerConfigs(full, found);
    else if (name === 'wrangler.json' || name === 'wrangler.jsonc') found.push(full);
  }
  return found;
};

run('pnpm', ['exec', 'vinext', 'build']);

const clientDir = resolve('dist/client');
if (!existsSync(clientDir)) {
  console.error('Cloudflare deploy: dist/client was not generated by vinext build.');
  process.exit(1);
}

const configs = findWranglerConfigs(resolve('dist'));
if (!configs.length) {
  console.error('Cloudflare deploy: no generated dist/**/wrangler.json was found.');
  process.exit(1);
}

const configPath = configs.find((p) => p.includes(`${process.platform === 'win32' ? '\\' : '/'}server${process.platform === 'win32' ? '\\' : '/'}`)) ?? configs[0];
let config;
try {
  config = JSON.parse(readFileSync(configPath, 'utf8'));
} catch (error) {
  console.error(`Cloudflare deploy: could not parse ${configPath}:`, error);
  process.exit(1);
}

let assetsDir = relative(dirname(configPath), clientDir).replaceAll('\\', '/');
if (!assetsDir.startsWith('.')) assetsDir = `./${assetsDir}`;

config.assets = {
  ...(config.assets ?? {}),
  directory: assetsDir,
  binding: config.assets?.binding ?? 'ASSETS',
};

if (!config.main) {
  const generatedEntry = resolve(dirname(configPath), 'index.js');
  if (existsSync(generatedEntry)) config.main = './index.js';
}

if (!config.main) {
  console.error(`Cloudflare deploy: generated config ${configPath} has no Worker main entry.`);
  process.exit(1);
}

writeFileSync(configPath, `${JSON.stringify(config, null, 2)}\n`);
console.log(`Cloudflare deploy: using ${configPath}`);
console.log(`Cloudflare deploy: static assets = ${assetsDir}`);

run('pnpm', ['exec', 'wrangler', 'deploy', '--config', configPath]);
